export type Translation = (
  key: TranslationKey,
  values?: TranslationValues,
) => string

export const LANGUAGE_OPTIONS = [
  { locale: 'sv', flag: '🇸🇪', label: 'Svenska' },
  { locale: 'en-GB', flag: '🇬🇧', label: 'English (United Kingdom)' },
  { locale: 'zh-Hans', flag: '🇨🇳', label: '简体中文' },
] as const satisfies ReadonlyArray<{
  locale: Locale
  flag: string
  label: string
}>

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  return messages[locale][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => {
    const value = values?.[name]
    if (value === undefined) {
      throw new Error(`Missing "${name}" value for translation "${key}".`)
    }
    return String(value)
  })
}
